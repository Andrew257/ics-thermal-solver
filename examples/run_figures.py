# Figure numbering used throughout
# ----------------------------------------------------------------------
#  Figure 1   system schematic (not generated by this script)
#  Figure 2   Test A  temperature trajectories
#  Figure 3   Test A  internode heat flow
#  Figure 4   Test A  constraint heat flows
#  Figure 5   Test A  phase planes
#  Figure 6   Test A  constraint-activation timeline
#  Figure 7   Test A  Newton iterations per macrostep
#  Figure 8   Test B  temperature trajectories
#  Figure 9   Test B  constraint-activation raster
#  Figure 10  Test B  Newton iterations per macrostep
#  Figure 11  Test C  temperature trajectories
