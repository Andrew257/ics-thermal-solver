# Figures are written to the repository root with names that match the
# figure numbers in the manuscript.
REPO_ROOT = Path(__file__).resolve().parent.parent
OUTDIR = REPO_ROOT


def _save_all(names):
    """
    Save and close every open figure, in creation order.

    plot_compare_ics_pcs and plot_phase_planes_ics_pcs each leave several
    figures open at once, so plt.savefig() alone would capture whichever
    was created last rather than the one intended.  The figure numbers
    returned by plt.get_fignums() are in creation order, so zipping them
    with the caller's name list gives a stable, position-independent
    mapping.

    Raises if the number of names does not match the number of open
    figures, which catches a change in panel order immediately.
    """
    fignums = plt.get_fignums()
    if len(fignums) != len(names):
        raise RuntimeError(
            f"_save_all expected {len(names)} open figures, "
            f"found {len(fignums)}: {fignums}"
        )
    for num, name in zip(fignums, names):
        fig = plt.figure(num)
        out = OUTDIR / name
        fig.savefig(out, dpi=300, bbox_inches="tight")
        plt.close(fig)
        print(f"[+] {out}")


