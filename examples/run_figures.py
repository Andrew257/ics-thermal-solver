#  Figure 16  residual vs step size          (run_projection_study.py)
#
# Panel order within the plotting helpers, which determines the mapping:
#   plot_compare_ics_pcs       -> 1 temperatures, 2 internode flows,
#                                 3 constraint flows, 4 activation timeline
#   plot_phase_planes_ics_pcs  -> 1 phase-plane scatter,
#                                 2 activation heatmaps (ICS and PCS)
# ----------------------------------------------------------------------


def run_test_A():
    print("\n=== Running Test A (N=2) ===")
    t0 = time.perf_counter()
    ics, pcs = run_test_case("A", N=2, solver="both",
                             t_final=13.0, dt_ics=0.05, h_pcs=0.0002)
    t1 = time.perf_counter()
    print(f"ICS CPU = {t1 - t0:.3f}s, Newton iters = {sum(ics['n_iter'])}")
    print(f"PCS steps = {pcs['icount']}")

    # ---- Figures 2, 3, 4, 6 : comparison panels ----------------------
    plot_compare_ics_pcs(ics, pcs, nodes=[0, 1])
    _save_all([
        "fig02_testA_temperatures.png",          # Figure 2
        "fig03_testA_internode_heatflows.png",   # Figure 3
        "fig04_testA_constraint_heatflows.png",  # Figure 4
        "fig06_testA_activation_timeline.png",   # Figure 6
    ])

    # ---- Figures 5 : phase planes ------------------------------------
    plot_phase_planes_ics_pcs(ics, pcs)
    _save_all([
        "fig05_testA_phase_planes.png",          # Figure 5
        "figA_extra_activation_raster.png",      # not in the paper
    ])

    # ---- Figure 7 : Newton iterations --------------------------------
    plot_newton_iterations(ics)
    _save_all([
        "fig07_testA_newton_iterations.png",     # Figure 7
    ])

    return ics, pcs


